SOFTWARE = {"Utilities", "Software", "Design & Illustration", "Video Production", "Audio Production",
            "Animation & Modeling", "Photo Editing", "Web Publishing", "Software Training", "Game Development"}

MIN_SCORE = 60  # weighted votes needed before we name a genre


def genre_of(tags):
    if not tags:
        return None
    total = sum(tags.values()) or 1
    if sum(v for t, v in tags.items() if t in SOFTWARE) > 0.15 * total:
        return None
    score = {}
    for tag, votes in tags.items():
        if tag in TAGS:
            g, w = TAGS[tag]
            score[g] = score.get(g, 0) + votes * w
    if not score:
        return None
    g, best = max(score.items(), key=lambda kv: kv[1])
    return g if best >= MIN_SCORE else None


def main(paths):
    rows = {}
    for p in paths:
        for line in open(p, encoding="utf-8"):
            try:
                d = json.loads(line)
            except ValueError:
                continue
            appid, name = d.get("appid"), (d.get("name") or "").replace("\t", " ").strip()
            g = genre_of(d.get("tags") or {})
            if appid and name and g:
                rows[int(appid)] = (g, name)
    print("# appid\tgenre\tname  (generated by tools/build_genre_db.py from SteamSpy tag votes, https://steamspy.com)")
    for appid in sorted(rows):
        g, name = rows[appid]
        print(f"{appid}\t{g}\t{name}")
    print(f"{len(rows)} games", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1:])
